import mongoose from 'mongoose';

const AccessTokenSchema = new mongoose.Schema({
  token: {
    type: String,
    required: true,
    unique: true,
  },
  userId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true,
  },
  expiresAt: {
    type: Date,
    required: true,
  },
}, { timestamps: true });

const AccessToken = mongoose.model('AccessToken', AccessTokenSchema);

export default AccessToken;